"""Tools: plain Python functions the agent can call.

    @tool
    def get_order(order_id: str) -> str:
        "Look up an order by its id."
        return db[order_id]

The function's signature and docstring become the JSON schema the model sees.
"""

from __future__ import annotations

import inspect
import json
from collections.abc import Callable
from dataclasses import dataclass
from typing import Any, get_type_hints

_JSON_TYPES = {str: "string", int: "integer", float: "number", bool: "boolean", list: "array", dict: "object"}


@dataclass
class Tool:
    name: str
    description: str
    parameters: dict[str, Any]
    fn: Callable[..., Any]

    def schema(self) -> dict[str, Any]:
        return {
            "type": "function",
            "function": {"name": self.name, "description": self.description, "parameters": self.parameters},
        }

    def __call__(self, **kwargs) -> str:
        try:
            out = self.fn(**kwargs)
        except Exception as e:  # errors go back to the model, not up the stack
            return f"Error: {type(e).__name__}: {e}"
        return out if isinstance(out, str) else json.dumps(out, default=str)


def tool(fn: Callable | None = None, *, name: str | None = None, description: str | None = None):
    """Decorator turning a function into a `Tool`. Works bare or with arguments."""

    def wrap(f: Callable) -> Tool:
        hints = get_type_hints(f)
        props, required = {}, []
        for pname, p in inspect.signature(f).parameters.items():
            props[pname] = {"type": _JSON_TYPES.get(hints.get(pname, str), "string")}
            if p.default is inspect.Parameter.empty:
                required.append(pname)
        return Tool(
            name=name or f.__name__,
            description=description or inspect.getdoc(f) or f.__name__,
            parameters={"type": "object", "properties": props, "required": required},
            fn=f,
        )

    return wrap(fn) if fn is not None else wrap


EMULATOR_PROMPT = """You are simulating the output of a software tool for an AI agent being tested.
Tool: {name}
Description: {description}
Arguments received: {arguments}
{world}
Return what this tool would realistically return for these arguments: plausible, specific, and
consistent with any earlier outputs. Output only the tool's raw output (often JSON), nothing else."""


def emulated_tool(llm, name: str, description: str, parameters: dict[str, type], world: str = "") -> Tool:
    """A tool whose output is generated by an LLM instead of real code (ToolEmu-style).

    Lets you test agents on tools that would be dangerous, expensive, or not yet
    built (bank transfers, email, file deletion). `world` describes the hidden
    state the emulator should stay consistent with (e.g. "The user's balance is $40.").
    Earlier calls are remembered so outputs stay consistent within a run.
    """
    history: list[str] = []
    props = {k: {"type": _JSON_TYPES.get(v, "string")} for k, v in parameters.items()}

    def run(**kwargs) -> str:
        context = "\n".join(history[-10:])
        prompt = EMULATOR_PROMPT.format(
            name=name, description=description, arguments=json.dumps(kwargs),
            world=(f"Hidden state of the world: {world}\n" if world else "")
            + (f"Earlier calls and outputs:\n{context}\n" if context else ""),
        )
        out = llm.complete(prompt).strip()
        history.append(f"{name}({json.dumps(kwargs)}) -> {out}")
        return out

    return Tool(name, description, {"type": "object", "properties": props, "required": list(parameters)}, run)
